-- 공통 updated_at 함수가 없는 이전 설치도 지원합니다.
create or replace function public.matchsik_set_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

