-- 기존 JSON 설정을 정규화된 배정으로 1회 변환합니다.
-- 이미 수동 배정된 강사는 건드리지 않습니다.
insert into public.teacher_course_assignments(teacher_id, certificate_code, course_type, active)
select distinct
  t.id,
  c.code,
  allowed.course,
  true
from public.teachers t
join public.certificate_catalog c
  on c.active = true
 and coalesce(t.groups,'[]'::jsonb) ? c.group_name
cross join lateral jsonb_array_elements_text(c.allowed_courses) as allowed(course)
where coalesce(t.courses,'[]'::jsonb) ? allowed.course
  and not exists(
    select 1 from public.teacher_course_assignments x where x.teacher_id = t.id
  )
on conflict (teacher_id,certificate_code,course_type) do nothing;

-- 정규화된 배정을 기존 화면용 teachers JSON에도 동기화하는 함수
create or replace function public.matchsik_sync_teacher_assignment_json(p_teacher_id text)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.teachers t
  set
    certifications = coalesce((
      select jsonb_agg(distinct c.name order by c.name)
      from public.teacher_course_assignments a
      join public.certificate_catalog c on c.code = a.certificate_code
      where a.teacher_id = p_teacher_id and a.active = true and c.active = true
    ), '[]'::jsonb),
    teaching_assignments = coalesce((
      select jsonb_agg(row_data order by cert_name)
      from (
        select
          c.name as cert_name,
          jsonb_build_object(
            'cert', c.name,
            'certificateCode', c.code,
            'courses', jsonb_agg(a.course_type order by a.course_type)
          ) as row_data
        from public.teacher_course_assignments a
        join public.certificate_catalog c on c.code = a.certificate_code
        where a.teacher_id = p_teacher_id and a.active = true and c.active = true
        group by c.name, c.code
      ) q
    ), '[]'::jsonb),
    groups = coalesce((
      select jsonb_agg(distinct c.group_name order by c.group_name)
      from public.teacher_course_assignments a
      join public.certificate_catalog c on c.code = a.certificate_code
      where a.teacher_id = p_teacher_id and a.active = true and c.active = true
    ), '[]'::jsonb),
    courses = coalesce((
      select jsonb_agg(distinct a.course_type order by a.course_type)
      from public.teacher_course_assignments a
      where a.teacher_id = p_teacher_id and a.active = true
    ), '[]'::jsonb),
    updated_at = now()
  where t.id = p_teacher_id;
end;
$$;

revoke all on function public.matchsik_sync_teacher_assignment_json(text)
from public, anon, authenticated;
grant execute on function public.matchsik_sync_teacher_assignment_json(text)
to service_role;


-- 관리자와 강사 포털이 동일한 저장 로직을 사용하도록 한 트랜잭션 함수
create or replace function public.matchsik_save_teacher_profile_secure(
  p_old_id text,
  p_profile jsonb,
  p_assignments jsonb,
  p_actor_user_id uuid default null,
  p_actor_email text default '',
  p_actor_role text default 'ADMIN'
)
returns public.teachers
language plpgsql
security definer
set search_path = public
as $$
declare
  v_new_id text := coalesce(nullif(btrim(p_profile->>'id'),''), p_old_id);
  v_name text := btrim(coalesce(p_profile->>'name',''));
  v_teacher public.teachers%rowtype;
  assignment_item jsonb;
  course_item text;
  cert_code text;
begin
  if v_new_id is null or v_new_id !~ '^[A-Za-z0-9_-]{2,80}$' then
    raise exception using errcode='P0001', message='강사 ID는 영문 대·소문자, 숫자, 하이픈, 밑줄만 사용할 수 있습니다.';
  end if;
  if v_name='' then
    raise exception using errcode='P0001', message='강사 이름이 필요합니다.';
  end if;
  if jsonb_typeof(coalesce(p_assignments,'[]'::jsonb)) <> 'array' then
    raise exception using errcode='P0001', message='수업 참여 자격증 형식이 올바르지 않습니다.';
  end if;

  if p_old_id is not null and exists(select 1 from public.teachers where id=p_old_id) then
    if p_old_id<>v_new_id and exists(select 1 from public.teachers where id=v_new_id) then
      raise exception using errcode='23505', message='이미 사용 중인 강사 ID입니다.';
    end if;
    if p_old_id<>v_new_id then
      update public.teachers set id=v_new_id, updated_at=now() where id=p_old_id;
    end if;
  elsif exists(select 1 from public.teachers where id=v_new_id) then
    null;
  else
    insert into public.teachers(id,name,role,groups,specialties,courses,tags,active,certifications,teaching_assignments)
    values(v_new_id,v_name,'자격증 전문 강사','[]'::jsonb,'[]'::jsonb,'[]'::jsonb,'[]'::jsonb,true,'[]'::jsonb,'[]'::jsonb);
  end if;

  update public.teachers
  set
    name=v_name,
    role=coalesce(p_profile->>'role',''),
    specialties=case when jsonb_typeof(p_profile->'specialties')='array' then p_profile->'specialties' else '[]'::jsonb end,
    tags=case when jsonb_typeof(p_profile->'tags')='array' then p_profile->'tags' else '[]'::jsonb end,
    teaching_style=coalesce(p_profile->>'teachingStyle',''),
    profile_image_url=coalesce(p_profile->>'profileImageUrl',''),
    career_summary=coalesce(p_profile->>'careerSummary',''),
    verified_title=coalesce(p_profile->>'verifiedTitle',''),
    completed_lessons=greatest(0,coalesce(nullif(p_profile->>'completedLessons','')::integer,0)),
    active=case when p_actor_role='TEACHER' then active else coalesce((p_profile->>'active')::boolean,true) end,
    sort_order=case when p_actor_role='TEACHER' then sort_order else coalesce(nullif(p_profile->>'sortOrder','')::integer,sort_order,100) end,
    updated_at=now()
  where id=v_new_id;

  delete from public.teacher_course_assignments where teacher_id=v_new_id;

  for assignment_item in select value from jsonb_array_elements(coalesce(p_assignments,'[]'::jsonb)) loop
    cert_code := btrim(coalesce(assignment_item->>'certificateCode',''));
    if cert_code='' then
      raise exception using errcode='P0001', message='자격증 코드가 누락되었습니다.';
    end if;
    if jsonb_typeof(assignment_item->'courses') <> 'array' then
      raise exception using errcode='P0001', message='수업 과정 형식이 올바르지 않습니다.';
    end if;
    for course_item in select value from jsonb_array_elements_text(assignment_item->'courses') loop
      insert into public.teacher_course_assignments(
        teacher_id,certificate_code,course_type,active,updated_by
      ) values(v_new_id,cert_code,course_item,true,p_actor_user_id);
    end loop;
  end loop;

  perform public.matchsik_sync_teacher_assignment_json(v_new_id);

  if to_regclass('public.audit_logs') is not null then
    insert into public.audit_logs(actor_user_id,actor_email,action,entity_type,entity_id,details)
    values(
      p_actor_user_id,p_actor_email,
      case when p_actor_role='TEACHER' then 'TEACHER_SELF_PROFILE_SAVED' else 'ADMIN_TEACHER_PROFILE_SAVED' end,
      'teacher',v_new_id,
      jsonb_build_object('oldId',p_old_id,'newId',v_new_id,'assignmentCount',jsonb_array_length(coalesce(p_assignments,'[]'::jsonb)))
    );
  end if;

  select * into v_teacher from public.teachers where id=v_new_id;
  return v_teacher;
exception
  when others then
    raise;
end;
$$;

