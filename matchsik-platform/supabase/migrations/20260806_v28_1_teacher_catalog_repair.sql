select
  tu.email,
  tu.teacher_id,
  tu.active as login_active,
  (t.id is not null) as profile_exists,
  t.name,
  t.active as public_visible,
  coalesce(jsonb_array_length(t.teaching_assignments),0) as assignment_count
from public.teacher_users tu
left join public.teachers t on t.id = tu.teacher_id
where lower(tu.email) in ('hj@naver.com','hm@naver.com','mg@naver.com')
order by tu.email;
