-- 카탈로그에서 허용하지 않은 과정은 DB 단계에서도 차단합니다.
create or replace function public.matchsik_validate_teacher_assignment()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  allowed jsonb;
begin
  select allowed_courses into allowed
  from public.certificate_catalog
  where code = new.certificate_code and active = true;

  if allowed is null then
    raise exception using errcode = 'P0001', message = '활성 자격증 정보를 찾을 수 없습니다.';
  end if;

  if not (allowed ? new.course_type) then
    raise exception using errcode = 'P0001', message = '해당 자격증에서 운영하지 않는 과정입니다.';
  end if;

  return new;
end;
$$;

drop trigger if exists trg_validate_teacher_assignment on public.teacher_course_assignments;
create trigger trg_validate_teacher_assignment
before insert or update on public.teacher_course_assignments
for each row execute function public.matchsik_validate_teacher_assignment();

